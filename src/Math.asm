; Binary logarithm
; b = antilogarithm exponent
; hl = antilogarithm significand (precision: 9 bits)
; b <- logarithm characteristic
; hl <- logarithm mantissa (precision: 8 bits)
Math_Log2:
	add hl,hl
	dec b
	jr nc,Math_Log2
	inc b
	ld l,h
	ld h,Math_log2Table >> 8
	ld h,(hl)
	ld l,0
	ret

